#!/usr/bin/env python3
"""Lift the firmware MP3 decoder MultiStream runs on its DSP SPU.

MultiStream reads /dev_flash/sys/external/flashMP3.pic (an SPU ELF from the
user's own firmware) into memory and DMAs its text segment into its DSP's
local store at 0x19F00, entering it at 0x21320. Run by the SPU interpreter it
falls behind: a quarter to two fifths of the audio blocks come out empty while
music plays. This lifts the text segment at that address and writes a
registration file that binds the lift to the segment's first 16 bytes, with
the code bytes compared before the first dispatch.

Usage: lift_flashmp3.py <flashMP3.pic> <ps3recomp dir> <out dir>
Writes <out>/spu_recomp.{c,h} and <out>/flashmp3_register.c.
"""
import os
import struct
import subprocess
import sys

LOAD_LSA = 0x19F00        # where MultiStream puts the text segment
TEXT_VADDR = 0x80         # the segment's vaddr in the PIC
IMAGE_ID = 950
PREFIX = 'flashmp3_'


def text_segment(pic):
    phoff = struct.unpack('>I', pic[0x1C:0x20])[0]
    phnum = struct.unpack('>H', pic[0x2C:0x2E])[0]
    entry = struct.unpack('>I', pic[0x18:0x1C])[0]
    for i in range(phnum):
        p_type, off, vaddr, _, filesz, _, flags, _ = struct.unpack(
            '>IIIIIIII', pic[phoff + i * 32:phoff + i * 32 + 32])
        if p_type == 1 and flags & 1:
            if vaddr != TEXT_VADDR:
                raise SystemExit(f'text segment at vaddr {vaddr:#x}, expected {TEXT_VADDR:#x}')
            return pic[off:off + filesz], entry
    raise SystemExit('no executable segment')


def main():
    pic_path, sdk, out = sys.argv[1:4]
    tools = os.path.join(sdk, 'tools')
    sys.path.insert(0, tools)
    from wrap_spu_elf import wrap

    code, entry = text_segment(open(pic_path, 'rb').read())
    base = LOAD_LSA                        # LS address of the segment's first byte
    entry_lsa = LOAD_LSA - TEXT_VADDR + entry
    os.makedirs(out, exist_ok=True)
    elf_path = os.path.join(out, 'flashmp3_text.elf')
    with open(elf_path, 'wb') as f:
        f.write(wrap(code, base=base, entry=entry_lsa))

    cmd = [sys.executable, os.path.join(tools, 'spu_lifter.py'), '--auto-functions', elf_path,
           '--base', hex(base), '--symbol-prefix', PREFIX, '-o', out,
           '--source-name', 'spu_recomp.c', '--header-name', 'spu_recomp.h',
           '--extra-funcs', hex(entry_lsa), '--report', os.path.join(out, 'lift.json')]
    r = subprocess.run(cmd, capture_output=True, text=True)
    with open(os.path.join(out, 'lift.log'), 'w') as f:
        f.write(r.stdout + r.stderr)
    if r.returncode:
        raise SystemExit('spu_lifter failed; see lift.log')

    lines = [
        '/* flashmp3_register.c -- GENERATED by tools/lift_flashmp3.py from the user\'s',
        ' * flashMP3.pic. Holds the decoder\'s code bytes; not committed. */',
        '#include <stdint.h>',
        '#include <stdio.h>',
        '#include "spu_overlay_residency.h"',
        '',
        'extern void spu_begin_image(int image_id);',
        f'extern void {PREFIX}spu_recomp_register(void);',
        '',
        f'static const uint8_t flashmp3_code[{len(code)}] = {{',
    ]
    for k in range(0, len(code), 16):
        lines.append('    ' + ','.join(f'0x{x:02X}' for x in code[k:k + 16]) + ',')
    lines += [
        '};',
        '',
        '__attribute__((constructor)) static void flashmp3_register(void)',
        '{',
        f'    static const spu_overlay_code_segment seg = {{0x{base:X}u, sizeof flashmp3_code, flashmp3_code}};',
        f'    spu_begin_image({IMAGE_ID});',
        f'    {PREFIX}spu_recomp_register();',
        '    spu_begin_image(0);',
        f'    if (!spu_overlay_register_verified_sig(flashmp3_code, 0x{base:X}u, sizeof flashmp3_code,',
        f'                                           {IMAGE_ID}, &seg, 1))',
        '        fprintf(stderr, "[flashmp3] decoder lift not registered, interpreted\\n");',
        '}',
        '',
    ]
    with open(os.path.join(out, 'flashmp3_register.c'), 'w') as f:
        f.write('\n'.join(lines))
    print(f'lifted {len(code):#x} bytes at {base:#x}, entry {entry_lsa:#x}')


if __name__ == '__main__':
    main()
